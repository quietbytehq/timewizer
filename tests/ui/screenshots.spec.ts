import { expect, test, type Page } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import { buildTimetable, setDialog, cellsWhere, go, importSample, lessonChip, newSchool, openApp, openTimetable, pickEntity, pickUp, pickView, setImproveSeconds, shot, type Theme } from './helpers'

// A walk through the whole app in light and dark mode. Run with UPDATE_SHOTS=1 to refresh docs/screenshots.
async function tour(page: Page, theme: Theme) {
  const errors = await openApp(page, theme)
  let n = 0
  const snap = async (name: string, full = true) => shot(page, theme, `${String(++n).padStart(2, '0')}-${name}`, { full })

  await snap('welcome')
  await newSchool(page, 'Riverside Secondary School')
  await go(page, 'School')
  await page.getByLabel('Academic year').fill('2026-27')
  await setDialog(page, { open: path.resolve('tests/ui/fixtures/logo.png') })
  await page.getByRole('button', { name: 'Choose a picture…' }).click()
  await expect(page.getByAltText('School logo')).toBeVisible()
  await snap('school')
  await go(page, 'Working days'); await snap('working-days')
  await go(page, 'Shifts & bells'); await snap('shifts-and-bells')
  await importSample(page)
  await snap('import-done')
  await go(page, 'Rules & limits'); await snap('rules-and-limits')
  await go(page, 'Subjects'); await snap('subjects')
  await go(page, 'Teachers')
  await page.getByRole('button', { name: /Ayesha Khan/ }).click()
  await page.getByRole('button', { name: 'Fri', exact: true }).first().click()
  await page.getByLabel('Mon period 1: Available').click()
  await snap('teachers-time-off')
  await go(page, 'Classes'); await snap('classes')
  await go(page, 'Rooms'); await snap('rooms')
  // a new, empty class so that the copy preview has something to show
  await go(page, 'Classes')
  await page.getByRole('button', { name: 'Add class' }).click()
  await page.getByPlaceholder('Grade 5 A').fill('Grade 6 C')
  await page.getByPlaceholder('5A', { exact: true }).fill('6C')
  await go(page, 'Lessons')
  await page.getByRole('button', { name: /English · 6A/ }).click()
  await page.getByLabel('Add a lesson that happens at the same time').selectOption({ label: 'Mathematics · 6B · BAH · 5 × 1' })
  await snap('lessons-with-link')
  await page.getByRole('button', { name: 'Remove link' }).click()
  await page.getByRole('button', { name: /Copy lessons to other classes/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Copy lessons to other classes' })
  await dialog.getByLabel('Copy from').selectOption({ label: 'Grade 6 A (9 lessons)' })
  await dialog.getByRole('checkbox', { name: /Grade 6 C/ }).check()
  await snap('copy-lessons-preview', false)
  await page.keyboard.press('Escape')
  await go(page, 'Workload'); await snap('workload')
  await go(page, 'Check before building'); await snap('check-ok')
  await go(page, 'Rules & limits')
  await page.getByLabel('Most periods per week').fill('12')
  await go(page, 'Check before building'); await snap('check-problems')
  await go(page, 'Rules & limits')
  await page.getByLabel('Most periods per week').fill('')
  await setImproveSeconds(page, 2)
  await buildTimetable(page)
  await snap('build-done')

  await openTimetable(page)
  await pickEntity(page, /Grade 6 A/)
  await snap('timetable-class')
  await pickUp(page, lessonChip(page, 'Science'))
  await expect(cellsWhere(page, 'danger').first()).toBeVisible()
  await snap('timetable-dragging', false)
  await page.mouse.up()
  await pickView(page, 'Teacher'); await pickEntity(page, /Bilal Ahmed/); await snap('timetable-teacher')
  await pickView(page, 'Room'); await pickEntity(page, /Computer Lab/); await snap('timetable-room')
  await pickView(page, 'Master'); await snap('timetable-master')
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await snap('timetable-master-zoomed')

  // room picker: allow a second room for the computer lesson first
  await go(page, 'Lessons')
  await page.getByRole('button', { name: /Computer Studies · 6A/ }).click()
  await page.getByLabel('Science Lab').check()
  await openTimetable(page)
  await pickView(page, 'Class'); await pickEntity(page, /Grade 6 A/)
  const chip = lessonChip(page, 'Computer Studies')
  await chip.hover()
  await chip.getByRole('button', { name: 'Choose room' }).click()
  await snap('room-picker', false)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Improve quality' }).click()
  await expect(page.getByText(/Timetable quality/)).toBeVisible({ timeout: 30_000 })
  await snap('timetable-improved')
  // print and export, and (when refreshing the pictures) example files to look at
  await go(page, 'Print & export')
  await expect(page.getByLabel('Preview of the page')).toBeVisible()
  await snap('print-and-export')
  if (process.env.UPDATE_SHOTS && theme === 'light') {
    const dir = path.resolve('docs/examples')
    fs.mkdirSync(dir, { recursive: true })
    await page.getByLabel('All teachers', { exact: true }).uncheck()
    await page.getByLabel('All rooms', { exact: true }).uncheck()
    await setDialog(page, { save: path.join(dir, 'Riverside-timetables.pdf') })
    await page.getByRole('button', { name: 'Save PDF…' }).click()
    await expect(page.getByRole('status')).toContainText('Saved a PDF')
    await page.getByLabel('All classes', { exact: true }).uncheck()
    await page.getByLabel('Paper size').selectOption('a3')
    await setDialog(page, { open: dir })
    await page.getByRole('button', { name: /Save pictures/ }).click()
    await expect(page.getByRole('status')).toContainText('Saved 1 picture')
    await setDialog(page, { save: path.join(dir, 'Riverside-timetable.xlsx') })
    await page.getByRole('button', { name: 'Save Excel…' }).click()
    await expect(page.getByRole('status')).toContainText('Excel')
    await setDialog(page, { save: path.join(dir, 'Riverside-timetable.csv') })
    await page.getByRole('button', { name: 'Save CSV…' }).click()
    await expect(page.getByRole('status')).toContainText('list of lessons')
  }
  expect(errors).toEqual([])
}

for (const theme of ['light', 'dark'] as Theme[]) {
  test(`screenshot tour, ${theme} mode`, async ({ page }) => {
    test.setTimeout(240_000)
    await tour(page, theme)
  })
}

test('a narrower window (1000 px) still reads well', async ({ page }) => {
  await page.setViewportSize({ width: 1000, height: 760 })
  const errors = await openApp(page, 'light')
  await newSchool(page, 'Riverside Secondary School')
  await importSample(page)
  await setImproveSeconds(page, 1)
  await buildTimetable(page)
  await go(page, 'Lessons'); await shot(page, 'light', 'narrow-lessons')
  await openTimetable(page); await pickEntity(page, /Grade 6 A/); await shot(page, 'light', 'narrow-timetable')
  await pickView(page, 'Master'); await shot(page, 'light', 'narrow-master')
  expect(errors).toEqual([])
})
